/* openapi-regenerated: regenerate packages/api/openapi.json, then CI runs
 * git diff --exit-code — the committed file must match what the code generates.
 * Until CMP-2's routes exist, the generator emits the committed empty document;
 * CMP-2's first part replaces this with generation from the Fastify route schemas. */
import { writeFile } from 'node:fs/promises'

const document = {
  openapi: '3.1.0',
  info: {
    title: 'Entra Sign-In Reports API',
    version: '0.1.0',
    description: 'Generated by npm run openapi — regenerated and diffed in CI. Routes arrive with CMP-2.',
  },
  paths: {},
}

await writeFile('packages/api/openapi.json', `${JSON.stringify(document, null, 2)}\n`)
console.log('packages/api/openapi.json regenerated')
